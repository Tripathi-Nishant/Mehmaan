from uuid import uuid4

from fastapi import APIRouter, Form, Request
from fastapi.responses import HTMLResponse, RedirectResponse
from jinja2 import Environment, PackageLoader
from sqlalchemy import select

from app.auth import (
    SESSION_COOKIE,
    create_session,
    delete_session,
    hash_password,
    verify_password,
)
from app.db.models import Host, Traveler, UserAccount
from app.db.session import session_factory

router = APIRouter(prefix="/auth")
templates = Environment(loader=PackageLoader("app.web", "templates"))


@router.get("/login", response_class=HTMLResponse)
async def login_page(request: Request):
    return templates.get_template("login.html").render(request=request, error=None)


@router.post("/login")
async def login(email: str = Form(), password: str = Form()):
    async with session_factory() as db:
        user = await db.scalar(
            select(UserAccount).where(UserAccount.email == email.strip().lower())
        )
        if not user or not verify_password(password, user.password_hash):
            return HTMLResponse(
                templates.get_template("login.html").render(
                    error="Email or password is incorrect."
                ),
                status_code=401,
            )
        token = await create_session(db, user)
    response = RedirectResponse("/account", status_code=303)
    response.set_cookie(SESSION_COOKIE, token, httponly=True, samesite="lax", max_age=14 * 86400)
    return response


@router.get("/register", response_class=HTMLResponse)
async def register_page(request: Request):
    return templates.get_template("register.html").render(request=request, error=None)


@router.post("/register")
async def register(
    name: str = Form(),
    email: str = Form(),
    password: str = Form(),
    role: str = Form(default="traveler"),
):
    email = email.strip().lower()
    if role not in {"traveler", "host"} or len(password) < 8:
        return HTMLResponse(
            templates.get_template("register.html").render(
                error="Use a valid role and password of at least 8 characters."
            ),
            status_code=400,
        )
    async with session_factory() as db:
        if await db.scalar(select(UserAccount).where(UserAccount.email == email)):
            return HTMLResponse(
                templates.get_template("register.html").render(
                    error="An account with this email already exists."
                ),
                status_code=409,
            )
        if role == "traveler":
            person = Traveler(name=name.strip(), email=email)
            db.add(person)
            await db.flush()
            user = UserAccount(
                email=email,
                password_hash=hash_password(password),
                role=role,
                display_name=name.strip(),
                traveler_id=person.id,
            )
        else:
            synthetic_id = -int(uuid4().int % 2_000_000_000)
            person = Host(
                telegram_user_id=synthetic_id,
                telegram_chat_id=synthetic_id,
                display_name=name.strip(),
            )
            db.add(person)
            await db.flush()
            user = UserAccount(
                email=email,
                password_hash=hash_password(password),
                role=role,
                display_name=name.strip(),
                host_id=person.id,
            )
        db.add(user)
        # UserAccount.id is generated by SQLAlchemy. Flush before creating the
        # session so AuthSession.user_id is never inserted as NULL.
        await db.flush()
        token = await create_session(db, user)
    response = RedirectResponse("/account", status_code=303)
    response.set_cookie(SESSION_COOKIE, token, httponly=True, samesite="lax", max_age=14 * 86400)
    return response


@router.post("/logout")
async def logout(request: Request):
    async with session_factory() as db:
        await delete_session(db, request.cookies.get(SESSION_COOKIE))
    response = RedirectResponse("/", status_code=303)
    response.delete_cookie(SESSION_COOKIE)
    return response
